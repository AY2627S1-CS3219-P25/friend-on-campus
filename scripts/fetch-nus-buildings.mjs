import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_URL = 'https://www.nus-digital-twin.com/api/v1/buildings';
const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), '../apps/student-app/src/map/nusBuildingsData.ts');

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`${SOURCE_URL} returned ${response.status}`);
}
const records = await response.json();
if (!Array.isArray(records)) {
  throw new Error('Expected a JSON array of building records');
}

const rows = records
  .filter((r) => typeof r.name === 'string' && Number.isFinite(r.latitude) && Number.isFinite(r.longitude))
  .map((r) => `  { elementId: ${JSON.stringify(String(r.elementId))}, name: ${JSON.stringify(r.name.trim())}, latitude: ${r.latitude}, longitude: ${r.longitude} },`);

const today = new Date().toISOString().slice(0, 10);
const source = `/**
 * AI Assistance Disclosure:
 * Tool: Claude Code (model: Claude Opus 5.5), date: 2026-11-04
 * Scope: Generated by scripts/fetch-nus-buildings.mjs; do not edit by hand.
 * Author review: <to be completed by huangjiaxi1111>
 */
// AI-generated (edited by huangjiaxi1111)
// Snapshot of ${SOURCE_URL} taken ${today} (${rows.length} records).
// Data: NUS Digital Twin (City Syntax Lab), sourced from OpenStreetMap and Google Maps; it may contain inaccuracies.
import type { NusBuilding } from './nusBuildings';

export const NUS_BUILDING_RECORDS: NusBuilding[] = [
${rows.join('\n')}
];
`;

await writeFile(OUTPUT, source);
console.log(`Wrote ${rows.length} records to ${OUTPUT}`);
